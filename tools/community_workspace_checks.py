"""Real HTTP acceptance checks shared by the current community lab harness."""
def run_workspace_checks(Client, status, check, guest, alice, bob, admin, moderator):
    w = '/api/workspace/'
    page, _ = status('shared community page', guest, '/', 200)
    check('workspace and lab menus in shared page', 'id="admin-menu"' in page and 'data-page="lab"' in page and 'data-page="courses"' in page)
    script, _ = status('current workspace JS served', guest, '/assets/community.js', 200)
    check('normal APIs use fixed mode', "'/api/community/fixed'" in script and "'/api/workspace/fixed'" in script and "let mode='vuln'" not in script)
    for mode in ['fixed','vuln']:
        for path in ['activity','reports/601','applications/701','admin/users','admin/reports','admin/applications','admin/posts','admin/comments','debug/config']:
            status('workspace guest rejected '+mode+'/'+path, guest, w+mode+'/'+path, 401)
        status('public course catalog '+mode, guest, w+mode+'/courses', 200)
        for path, fields in [('reports',{'targetType':'POST','targetId':'101','reason':'guest'}),('courses/802/apply',{'reason':'guest'}),('admin/courses',{'title':'guest','description':'guest'}),('admin/users/2/edit',{'role':'ADMIN','state':'ACTIVE'})]:
            status('workspace guest write rejected '+mode+'/'+path,guest,w+mode+'/'+path,401,fields)
    status('invalid workspace mode',alice,w+'other/activity',404)
    data,_=status('own activity',alice,w+'fixed/activity',200)
    check('own activity excludes other reports and applications',all(r['OWNER_ID']==1 for k in ['reports','applications'] for r in data[k]))
    for route in ['admin/users','admin/reports','admin/applications','admin/posts','admin/comments']:
        status('ordinary user blocked '+route,alice,w+'fixed/'+route,403)
        status('moderator not global admin '+route,moderator,w+'fixed/'+route,403)
        status('admin reads '+route,admin,w+'fixed/'+route,200)
        status('lab omits role check '+route,alice,w+'vuln/'+route,200)
    status('own report',alice,w+'fixed/reports/601',200)
    status('other report hidden',alice,w+'fixed/reports/602',404)
    data,_=status('lab report idor',alice,w+'vuln/reports/602',200)
    check('idor returns bob report marker','BOB_REPORT_PRIVATE' in data['REASON'])
    status('admin report detail',admin,w+'fixed/reports/602',200)
    status('report CSRF required',alice,w+'fixed/reports',403,{'targetType':'POST','targetId':'101','reason':'report'},'')
    status('report other-user CSRF rejected',alice,w+'fixed/reports',403,{'targetType':'POST','targetId':'101','reason':'report'},bob.csrf)
    status('private post cannot be reported by nonreader',alice,w+'fixed/reports',404,{'targetType':'POST','targetId':'102','reason':'hidden'})
    status('bad report type',alice,w+'fixed/reports',400,{'targetType':'OTHER','targetId':'101','reason':'report'})
    status('missing report target',alice,w+'fixed/reports',404,{'targetType':'POST','targetId':'999999','reason':'report'})
    status('invalid report target id',alice,w+'fixed/reports',400,{'targetType':'POST','targetId':'invalid','reason':'report'})
    status('blank report reason',alice,w+'fixed/reports',400,{'targetType':'POST','targetId':'101','reason':' '})
    d,_=status('create own report',alice,w+'fixed/reports',200,{'targetType':'POST','targetId':'101','reason':'Alice new report'})
    report_id=d['id']
    status('other user cannot read new report',bob,w+f'fixed/reports/{report_id}',404)
    status('user cannot process report',alice,w+f'fixed/admin/reports/{report_id}/review',403,{'decision':'RESOLVED','resolution':'bypass'})
    d,_=status('denied report process preserves state',alice,w+f'fixed/reports/{report_id}',200)
    check('report stays pending',d['STATE']=='PENDING')
    status('admin report csrf required',admin,w+f'fixed/admin/reports/{report_id}/review',403,{'decision':'RESOLVED','resolution':'done'},'')
    status('invalid report decision',admin,w+f'fixed/admin/reports/{report_id}/review',400,{'decision':'OTHER','resolution':'done'})
    status('admin processes report',admin,w+f'fixed/admin/reports/{report_id}/review',200,{'decision':'RESOLVED','resolution':'verified'})
    d,_=status('reporter sees resolution',alice,w+f'fixed/reports/{report_id}',200)
    check('report resolution persists',d['STATE']=='RESOLVED' and d['RESOLUTION']=='verified')
    status('report cannot be processed twice',admin,w+f'fixed/admin/reports/{report_id}/review',409,{'decision':'REJECTED','resolution':'again'})
    status('lab csrf omission is observable',alice,w+'vuln/reports',200,{'targetType':'POST','targetId':'101','reason':'CSRF lab'},'')
    status('other application hidden',alice,w+'fixed/applications/702',404)
    status('lab application IDOR',alice,w+'vuln/applications/702',200)
    status('duplicate application rejected',alice,w+'fixed/courses/801/apply',409,{'reason':'duplicate'})
    status('application csrf required',alice,w+'fixed/courses/802/apply',403,{'reason':'test'},'')
    d,_=status('user applies to course',alice,w+'fixed/courses/802/apply',200,{'reason':'ALICE_NEW_APPLICATION'})
    aid=d['id']
    status('other user cannot cancel application',bob,w+f'fixed/applications/{aid}/cancel',404,{})
    status('user cannot approve course',alice,w+f'fixed/admin/applications/{aid}/review',403,{'decision':'APPROVED'})
    d,_=status('denied application mutation preserves state',alice,w+f'fixed/applications/{aid}',200)
    check('application stays pending',d['STATE']=='PENDING')
    status('admin course review csrf required',admin,w+f'fixed/admin/applications/{aid}/review',403,{'decision':'APPROVED'},'')
    status('invalid course review',admin,w+f'fixed/admin/applications/{aid}/review',400,{'decision':'OTHER'})
    status('admin accepts application',admin,w+f'fixed/admin/applications/{aid}/review',200,{'decision':'APPROVED'})
    status('course review replay rejected',admin,w+f'fixed/admin/applications/{aid}/review',409,{'decision':'REJECTED'})
    status('approved application cancellation rejected',alice,w+f'fixed/applications/{aid}/cancel',409,{})
    status('user cannot create course',alice,w+'fixed/admin/courses',403,{'title':'course','description':'description'})
    status('course creation csrf required',admin,w+'fixed/admin/courses',403,{'title':'course','description':'description'},'')
    d,_=status('admin creates course',admin,w+'fixed/admin/courses',200,{'title':'새 강의','description':'실습 강의'})
    cid=d['id']
    status('admin uses common application function',admin,w+f'fixed/courses/{cid}/apply',200,{'reason':'admin attendee'})
    d,_=status('admin sees own activity',admin,w+'fixed/activity',200)
    check('admin application recorded under admin',any(a['COURSE_ID']==cid and a['OWNER_ID']==3 for a in d['applications']))
    d,_=status('bob applies to new course',bob,w+f'fixed/courses/{cid}/apply',200,{'reason':'bob attendee'})
    bid=d['id']
    status('owner cancels pending application',bob,w+f'fixed/applications/{bid}/cancel',200,{})
    status('owner cannot cancel twice',bob,w+f'fixed/applications/{bid}/cancel',409,{})
    status('course invalid state',admin,w+f'fixed/admin/courses/{cid}/edit',400,{'title':'new','description':'description','state':'OTHER'})
    status('admin closes course',admin,w+f'fixed/admin/courses/{cid}/edit',200,{'title':'마감 강의','description':'description','state':'CLOSED'})
    status('closed course rejects application',alice,w+f'fixed/courses/{cid}/apply',409,{'reason':'late'})
    status('user cannot delete course',alice,w+f'fixed/admin/courses/{cid}/delete',403,{})
    status('admin deletes course',admin,w+f'fixed/admin/courses/{cid}/delete',200,{})
    status('deleted course hidden',guest,w+f'fixed/courses/{cid}',404)
    status('deleted course applications removed',bob,w+f'fixed/applications/{bid}',404)
    status('lab user can process another user application',alice,w+'vuln/admin/applications/702/review',200,{'decision':'REJECTED'})
    status('ordinary user cannot reset workspace',alice,w+'reset',403,{})
    status('reset csrf required',admin,w+'reset',403,{},'')
    status('reset restores learning data',admin,w+'reset',200,{})
    d,_=status('restored application',bob,w+'fixed/applications/702',200)
    check('application reset to pending',d['STATE']=='PENDING')
    status('user cannot change roles',alice,w+'fixed/admin/users/2/edit',403,{'role':'ADMIN','state':'ACTIVE'})
    status('invalid managed email rejected',admin,w+'fixed/admin/users/2/edit',400,{'role':'USER','state':'ACTIVE','email':'invalid'})
    status('admin updates member information',admin,w+'fixed/admin/users/2/edit',200,{'role':'USER','state':'ACTIVE','email':'bob-updated@lab.invalid'})
    d,_=status('member sees managed email update',bob,'/api/access/me',200)
    check('managed email persisted',d['user']['EMAIL']=='bob-updated@lab.invalid')
    status('restore member email',admin,w+'fixed/admin/users/2/edit',200,{'role':'USER','state':'ACTIVE','email':'bob@lab.invalid'})
    status('invalid role rejected',admin,w+'fixed/admin/users/2/edit',400,{'role':'ROOT','state':'ACTIVE'})
    status('recovery admin preserved',admin,w+'fixed/admin/users/3/edit',409,{'role':'USER','state':'SUSPENDED'})
    status('admin user management csrf required',admin,w+'fixed/admin/users/2/edit',403,{'role':'USER','state':'SUSPENDED'},'')
    status('admin suspends bob',admin,w+'fixed/admin/users/2/edit',200,{'role':'USER','state':'SUSPENDED'})
    status('existing bob session is blocked',bob,'/api/community/fixed/posts',403)
    status('suspended bob cannot log in',Client(),'/api/auth/login',403,{'username':'bob','password':'LabOnly!2026'})
    status('admin reactivates bob',admin,w+'fixed/admin/users/2/edit',200,{'role':'USER','state':'ACTIVE'})
    bob.login('bob')
    status('reactivated bob uses community',bob,w+'fixed/activity',200)
    status('admin grants bob admin role',admin,w+'fixed/admin/users/2/edit',200,{'role':'ADMIN','state':'ACTIVE'})
    status('role change applies to existing session',bob,w+'fixed/admin/users',200)
    status('admin restores bob role',admin,w+'fixed/admin/users/2/edit',200,{'role':'USER','state':'ACTIVE'})
    status('demotion applies to existing session',bob,w+'fixed/admin/users',403)
    d,_=status('new comment',alice,'/api/community/fixed/posts/101/comments',200,{'body':'ALICE_COMMENT'})
    comment=d['id']
    status('other user cannot edit comment',bob,f'/api/community/fixed/comments/{comment}/edit',403,{'body':'bypass'})
    status('other user cannot delete comment',bob,f'/api/community/fixed/comments/{comment}/delete',403,{})
    status('owner edits comment',alice,f'/api/community/fixed/comments/{comment}/edit',200,{'body':'ALICE_UPDATED'})
    status('comment can be reported',bob,w+'fixed/reports',200,{'targetType':'COMMENT','targetId':comment,'reason':'comment report'})
    status('admin deletes any comment',admin,f'/api/community/fixed/comments/{comment}/delete',200,{})
    status('deleted comment is 404',alice,f'/api/community/fixed/comments/{comment}/delete',404,{})
    injection="%' OR 1=1 -- "
    import urllib.parse
    d,_=status('fixed search binds input',alice,'/api/community/fixed/search?q='+urllib.parse.quote(injection),200)
    check('bound injection returns no hidden records',not d)
    d,_=status('lab search demonstrates injection',alice,'/api/community/vuln/search?q='+urllib.parse.quote(injection),200)
    check('injected search exposes bob record',any(p['ID']==102 for p in d))
    status('fixed config is protected',alice,w+'fixed/debug/config',403)
    d,_=status('lab exposes synthetic config',alice,w+'vuln/debug/config',200)
    check('config contains synthetic key only',d['trainingOnly'] and d['apiKey'].startswith('LAB_FAKE_'))
    status('workspace final reset',admin,w+'reset',200,{})
